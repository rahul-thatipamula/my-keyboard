    private const val KEY_RECENT = "emoji_recent"
    private const val MAX_RECENT = 40
    private const val SEP = ""

    fun recents(context: Context): List<String> {
        val raw = Prefs.get(context).getString(KEY_RECENT, "") ?: ""
        return if (raw.isEmpty()) emptyList() else raw.split(SEP)
    }

    fun addRecent(context: Context, emoji: String) {
        val list = ArrayList(recents(context))
        list.remove(emoji)
        list.add(0, emoji)
        while (list.size > MAX_RECENT) list.removeAt(list.size - 1)
        Prefs.get(context).edit().putString(KEY_RECENT, list.joinToString(SEP)).apply()
    }
